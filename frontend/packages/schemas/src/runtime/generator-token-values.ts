import { readPointer } from './json-pointer.ts';
import { toSourceRelativePointer } from './generator-token-regions.ts';

export type TokenValuesOptions = Readonly<{
  exportName: string;
  bindings: readonly Readonly<{
    path: readonly string[];
    sourcePointer: string;
    format?: 'literal' | 'milliseconds';
  }>[];
}>;
type ValueNode = string | number | boolean | { [key: string]: ValueNode };
const identifier = /^[a-zA-Z_$][\w$]*$/;
function hasItems(value: unknown): boolean {
  return Array.isArray(value) && value.length > 0;
}
const forbidden = new Set(['__proto__', 'constructor', 'prototype']);
function checkKey(key: string) {
  if (!identifier.test(key) || forbidden.has(key)) throw new Error('Token export identifier 非法');
}
function render(value: ValueNode, depth = 0): string {
  if (typeof value === 'string')
    return (
      "'" +
      value
        .replace(/\\/g, '\\\\')
        .replace(/'/g, "\\'")
        .replace(/\n/g, '\\n')
        .replace(/\r/g, '\\r') +
      "'"
    );
  if (typeof value !== 'object') return String(value);
  const inset = '  '.repeat(depth);
  return (
    '{\n' +
    Object.entries(value)
      .map(([key, child]) => `${inset}  ${key}: ${render(child, depth + 1)},`)
      .join('\n') +
    '\n' +
    inset +
    '}'
  );
}

/** Small JavaScript token exports keep authoring schemas out of the browser bundle. */
export function renderTokenValues(source: unknown, options: TokenValuesOptions): string {
  checkKey(options.exportName);
  if (!hasItems(options.bindings)) throw new Error('Token bindings 缺失');
  const result: { [key: string]: ValueNode } = {};
  for (const binding of options.bindings) {
    if (!hasItems(binding.path)) throw new Error('Token output path 缺失');
    binding.path.forEach(checkKey);
    const { found, value } = readPointer(source, toSourceRelativePointer(binding.sourcePointer));
    if (!found) throw new Error('Token Source Pointer 悬空');
    let projected: string | number | boolean;
    if (binding.format === 'milliseconds') {
      if (typeof value !== 'string' || !/^\d+(?:\.\d+)?(?:ms|s)$/.test(value))
        throw new Error('Token duration 单位必须是 ms 或 s');
      projected = parseFloat(value) * (value.endsWith('ms') ? 1 : 1000);
    } else {
      if (binding.format !== undefined && binding.format !== 'literal')
        throw new Error('Token format 非法');
      if (typeof value !== 'string' && typeof value !== 'number' && typeof value !== 'boolean')
        throw new Error('Token 值必须是 scalar');
      projected = value;
    }
    let current = result;
    for (const key of binding.path.slice(0, -1)) {
      if (current[key] === undefined) current[key] = {};
      const child = current[key];
      if (typeof child !== 'object') throw new Error('Token output path 冲突');
      current = child;
    }
    const key = binding.path.at(-1)!;
    if (current[key] !== undefined) throw new Error('Token output path 重复');
    current[key] = projected;
  }
  return `// @generated by @clouddrive/schemas/runtime ts-token-values-v1; run pnpm codegen:design.\nexport const ${options.exportName} = ${render(result)} as const;\n`;
}
